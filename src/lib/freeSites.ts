/** 検索用に文字をそろえる（全角英数→半角・小文字、カタカナ→ひらがな、長音や記号を除く） */
export function normalizeKana(s: string) {
  return s
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/[\s・！!.．ー\-ｰ]/g, "");
}

